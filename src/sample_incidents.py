def seed_sample_incidents():
    """Insert missing sample incidents and return the number added."""
    existing = get_all_incidents()
    existing_titles = {
        str(item.get("title", "")).strip().casefold()
        for item in existing
        if isinstance(item, dict)
    }
    added = 0
    for incident in SAMPLE_INCIDENTS:
        title_key = incident["title"].strip().casefold()
        if title_key in existing_titles:
            continue
        create_incident(**incident)
        existing_titles.add(title_key)
        added += 1
    return added
